class RotaryAttention(tf.keras.layers.Layer):
    def __init__(self, num_heads, d_model):
        super(RotaryAttention, self).__init__()
        self.num_heads = num_heads
        self.d_model = d_model
        assert d_model % num_heads == 0
        self.depth = d_model // num_heads

        self.wq = tf.keras.layers.Dense(d_model)
        self.wk = tf.keras.layers.Dense(d_model)
        self.wv = tf.keras.layers.Dense(d_model)
        self.out = tf.keras.layers.Dense(d_model)

    def split_heads(self, x):
        batch_size = tf.shape(x)[0]
        x = tf.reshape(x, (batch_size, -1, self.num_heads, self.depth))
        return tf.transpose(x, perm=[0, 2, 1, 3])  # [B, H, T, D]

    def apply_rope(self, x, seq_len):
        half_dim = self.depth // 2
        freqs = 1.0 / (10000 ** (tf.range(0, half_dim, dtype=tf.float32) / half_dim))
        positions = tf.range(seq_len, dtype=tf.float32)
        angles = tf.einsum('i,j->ij', positions, freqs)

        sin = tf.sin(angles)[None, None, :, :]
        cos = tf.cos(angles)[None, None, :, :]

        x1, x2 = tf.split(x, 2, axis=-1)
        x_rotated = tf.concat([x1 * cos - x2 * sin, x1 * sin + x2 * cos], axis=-1)
        return x_rotated

    def call(self, x, mask=None, kv_c=None):
        batch_size = tf.shape(x)[0]
        seq_len = tf.shape(x)[1]

        q = self.split_heads(self.wq(x))  # [B, H, T, D]
        k = self.split_heads(self.wk(x))
        v = self.split_heads(self.wv(x))

        # Apply Rotary Positional Embedding to q and k
        q = self.apply_rope(q, seq_len)
        k = self.apply_rope(k, seq_len)
        if kv_c is not None:
          k = tf.concat([kv_c['k'], k], axis=2)  # [B, H, T, D]
          v = tf.concat([kv_c['v'], v], axis=2)  # [B, H, T, D]

        logits = tf.matmul(q, k, transpose_b=True)  # [B, H, T, T]
        logits = logits / tf.math.sqrt(tf.cast(self.depth, tf.float32))

        # === Add causal mask here ===
        seq_len = tf.shape(x)[1]
        causal_mask = tf.linalg.band_part(tf.ones((seq_len, seq_len)), -1, 0)  # lower triangle
        causal_mask = 1.0 - causal_mask  # 1s where future tokens are masked
        logits += causal_mask[None, None, :, :] * -1e9  # broadcast across batch and heads

        # Optional: combine with external mask (e.g., padding)
        if mask is not None:
            logits += (mask * -1e9)

        attention_weights = tf.nn.softmax(logits, axis=-1)
        output = tf.matmul(attention_weights, v)  # [B, H, T, D]

        output = tf.transpose(output, perm=[0, 2, 1, 3])
        output = tf.reshape(output, (batch_size, seq_len, self.d_model))
        kv_c = {'k': k, 'v': v}
        return self.out(output), attention_weights

