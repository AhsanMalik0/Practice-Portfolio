class MoE(tf.keras.layers.Layer):
    def __init__(self, num_experts, d_model, d_ff, capacity_factor=1.25, activation='relu'):
        super(MoE, self).__init__()
        self.num_experts = num_experts
        self.d_model = d_model
        self.d_ff = d_ff
        self.capacity_factor = capacity_factor
        self.activation = tf.keras.activations.get(activation)

        # Define experts
        self.experts = [tf.keras.Sequential([
            tf.keras.layers.Dense(d_ff, activation=activation),
            tf.keras.layers.Dense(d_model)
        ]) for _ in range(num_experts)]

        # Gating network
        self.gate = tf.keras.layers.Dense(num_experts)

    def call(self, x):
        batch_size, seq_len, _ = tf.shape(x)[0], tf.shape(x)[1], tf.shape(x)[2]
        x_flat = tf.reshape(x, [-1, self.d_model])
        # Gating logits and softmax
        logits = self.gate(x_flat)  # [B*T, num_experts]
        gates = tf.nn.softmax(logits, axis=-1)

        # Top-1 routing
        top_expert_idx = tf.argmax(gates, axis=-1, output_type=tf.int32)  # [B*T]
        one_hot_mask = tf.one_hot(top_expert_idx, depth=self.num_experts)  # [B*T, E]

        # Capacity (maximum tokens per expert)
        tokens_per_expert = tf.math.reduce_sum(one_hot_mask, axis=0)
        capacity = tf.cast(tf.math.ceil(self.capacity_factor * tf.reduce_max(tokens_per_expert)), tf.int32)

        # Allocate tokens to experts
        expert_inputs = [list() for _ in range(self.num_experts)]

        for i in range(self.num_experts):
            indices = tf.where(top_expert_idx == i)
            selected = tf.gather_nd(x_flat, indices)
            expert_inputs[i] = tf.pad(selected, [[0, capacity - tf.shape(selected)[0]], [0, 0]])

        expert_inputs = tf.stack(expert_inputs)  # [E, capacity, D]

        # Expert outputs
        expert_outputs = []
        for i in range(self.num_experts):
            out = self.experts[i](expert_inputs[i])  # [capacity, D]
            expert_outputs.append(out)

        expert_outputs = tf.stack(expert_outputs)  # [E, capacity, D]

        # Gather outputs for top-1 assigned tokens
        final_outputs = tf.zeros_like(x_flat)
        for i in range(self.num_experts):
            indices = tf.where(top_expert_idx == i)
            selected_outputs = expert_outputs[i][:tf.shape(indices)[0]]
            final_outputs = tf.tensor_scatter_nd_update(final_outputs, indices, selected_outputs)

        return tf.reshape(final_outputs, [batch_size, seq_len, self.d_model])



