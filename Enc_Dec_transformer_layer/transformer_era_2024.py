def compute_edit_distance(predictions, labels):
    edit_distances = []
    for pred, label in zip(predictions, labels):
        pred_text = tokenizer.decode(pred, skip_special_tokens=True)
        label_text = tokenizer.decode(label, skip_special_tokens=True)
        edit_distances.append(Levenshtein.distance(pred_text, label_text))

    return sum(edit_distances) / len(edit_distances) if edit_distances else 0

def compute_bleu_score(predictions, labels):
    bleu_scores = []
    for pred, label in zip(predictions, labels):
        pred_text = tokenizer.decode(pred, skip_special_tokens=True)
        label_text = tokenizer.decode(label, skip_special_tokens=True)
        bleu_scores.append(sentence_bleu([label_text.split()], pred_text.split()))
    return sum(bleu_scores) / len(bleu_scores) if bleu_scores else 0

