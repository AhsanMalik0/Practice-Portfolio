class TransformerBlock(tf.keras.layers.Layer):
  def __init__(self, num_heads, dmodel):
    super(TransformerBlock, self).__init__()
    self.rmsnorm = keras.layers.RMSNormalization()
    self.rmsnorm1 = keras.layers.RMSNormalization()
    self.attention_layer = RotaryAttention(num_heads=num_heads, d_model=dmodel)
    self.ffn = tf.keras.Sequential([
        tf.keras.layers.Dense(units=dmodel*2),  # Must be 2 * d_model for SwiGLU
        SwiGLU(name='swiglu_activation'),
        tf.keras.layers.Dense(units=dmodel)
        ])
  def call(self, x):
    attn_out, _ = self.attention_layer(self.rmsnorm(x))
    x = x + attn_out
    x = x + self.ffn(self.rmsnorm1(x))
    return x

class OUT(tf.keras.layers.Layer):
  def __init__(self, num_heads, dmodel, vocab_size):
    super(OUT,self).__init__()
    self.Dense1 = keras.layers.Dense(units=dmodel*2)
    self.Dense2 = keras.layers.Dense(units=vocab_size)
    self.activation = SwiGLU(name='swiglu_activation')
  def call(self, x):
    return self.Dense2(self.activation(self.Dense1(x)))

